"""
explanation_agent.py — Agent 3: Synthesizes budget and risk analyses into an SRE decision and mitigations.

Uses an LLM when configured, with bounded timeouts and structured JSON validation.
Strictly falls back to high-precision deterministic rules if the LLM is unavailable,
times out, rate limits, or fails schema validation.
"""
from __future__ import annotations

import json
import logging
import os
import time
from typing import Any, Optional
from pydantic import BaseModel, Field

from ai.budget_agent import BudgetAgentOutput, BudgetStatus
from ai.risk_agent import RiskAgentOutput
from ai.prompts import EXPLANATION_AGENT_SYSTEM_PROMPT, EXPLANATION_USER_PROMPT_TEMPLATE

logger = logging.getLogger("releaseguard.explanation_agent")


class ExplanationAgentOutput(BaseModel):
    """Structured output from Explanation LLM Agent."""
    explanation: str = Field(..., description="Concise, evidence-based explanation of the release decision")
    mitigations: list[str] = Field(..., description="Concrete, actionable engineering mitigations")
    deployment_timing_advice: str = Field(..., description="Practical advice regarding calendar and timing")
    confidence_note: str = Field(..., description="Explicit note on the scope, limitations, and confidence of the assessment")
    is_fallback: bool = Field(default=False, description="True if generated by deterministic fallback rather than LLM")
    model_name: str = Field(default="deterministic-rule-fallback", description="LLM model or fallback identifier")
    generation_latency_ms: float = Field(default=0.0, description="Latency in milliseconds")


# ---------------------------------------------------------------------------
# High-Precision Deterministic Fallback Generator
# ---------------------------------------------------------------------------

def generate_fallback_explanation(
    *,
    risk_score: float,
    recommendation: str,
    budget_analysis: BudgetAgentOutput,
    risk_analysis: RiskAgentOutput,
    deployment_calendar_data: Optional[dict[str, Any]] = None,
    retrieved_policy_documents: Optional[list[dict[str, Any]]] = None,
    reason: str = "DEFAULT_FALLBACK",
) -> ExplanationAgentOutput:
    """
    Deterministic fallback generator for the Explanation Agent.
    Operates with zero network calls and provides calibrated SRE-grade guidance.
    """
    start_time = time.perf_counter()
    rec = recommendation.upper()

    cal = deployment_calendar_data or {}
    cal_advice = cal.get("advice") or "No special calendar constraint applies to this time slot."

    mitigations: list[str] = []

    if rec == "WAIT":
        reasons: list[str] = []
        if budget_analysis.status == BudgetStatus.EXHAUSTED:
            reasons.append(f"error budget is exhausted ({budget_analysis.summary})")
        elif budget_analysis.status == BudgetStatus.LOW:
            reasons.append(f"error budget is dangerously depleted ({budget_analysis.summary})")

        if risk_analysis.dominant_factor:
            reasons.append(f"elevated risk from {risk_analysis.dominant_factor}")
        if "FREEZE" in cal_advice.upper():
            reasons.append("active deployment freeze window is in effect")
        elif "PEAK" in cal_advice.upper():
            reasons.append("high-traffic peak period increases incident blast radius")

        reason_str = " and ".join(reasons) if reasons else f"elevated release risk profile (score {risk_score:.1f}/100)"

        explanation = (
            f"WAIT: Deployment is withheld because {reason_str}. "
            f"Proceeding now introduces high risk of violating SLA commitments. "
            f"{budget_analysis.summary}"
        )

        mitigations = [
            "Halt deployment until service reliability metrics recover and error budget burn rate drops below 1.0x.",
            "Investigate and remediate active telemetry degradation before deploying new changes.",
            "If change is an emergency P0 hotfix, escalate for SRE on-call lead and engineering manager written sign-off.",
            "Reschedule rollout for an approved low-risk maintenance window (e.g. Tuesday or Wednesday morning).",
        ]
        timing_advice = (
            f"Hold deployment. {cal_advice} "
            "Wait until blocking reliability concerns are investigated and error budget recovers."
        )

    elif rec == "GO_WITH_SAFE_GUARD":
        explanation = (
            f"GO WITH SAFEGUARDS: Release is permitted to proceed with mandatory safeguards (score {risk_score:.1f}/100). "
            f"{budget_analysis.summary} "
            f"Primary caution driver is {risk_analysis.dominant_factor or 'moderate telemetry risk'}."
        )
        mitigations = [
            "Implement canary rollout: Route 5% traffic for 15 minutes; advance only if error rate and p99 latency remain nominal.",
            "Validate automated rollback readiness and ensure one-click rollback procedure is pre-verified.",
            "Keep dedicated observability dashboards open and actively monitored by on-call during deployment.",
            "Ensure new functionality is encapsulated behind feature flags for instant deactivation.",
        ]
        timing_advice = (
            f"{cal_advice} Deploy during nominal traffic hours and allow at least 30 minutes of soak time before peak windows."
        )

    else:  # GO
        explanation = (
            f"GO: Release is cleared for standard automated deployment (risk score {risk_score:.1f}/100). "
            f"{budget_analysis.summary} "
            "Telemetry indicators and factor weights reside safely within nominal operating thresholds."
        )
        mitigations = [
            "Proceed through standard automated CI/CD pipeline.",
            "Observe telemetry during the initial 10-minute post-deployment soak period.",
            "Verify automated alerts are armed for latency and error anomalies.",
        ]
        timing_advice = f"{cal_advice} Standard deployment window applies."

    # Build confidence note acknowledging data limits
    limitations = risk_analysis.data_limitations + budget_analysis.warnings
    if limitations:
        confidence_note = f"Assessment limited to supplied metrics and sample data. Notes: {'; '.join(limitations[:2])}."
    else:
        confidence_note = "Assessment based on complete supplied telemetry and historical records."

    # Incorporate policy note if available
    if retrieved_policy_documents:
        source_names = list({doc.get("source", "policy") for doc in retrieved_policy_documents})
        confidence_note += f" Cross-referenced with policy guidelines ({', '.join(source_names)})."

    elapsed_ms = (time.perf_counter() - start_time) * 1000.0

    return ExplanationAgentOutput(
        explanation=explanation,
        mitigations=mitigations,
        deployment_timing_advice=timing_advice,
        confidence_note=confidence_note,
        is_fallback=True,
        model_name=f"deterministic-rule-fallback ({reason})",
        generation_latency_ms=round(elapsed_ms, 2),
    )


# ---------------------------------------------------------------------------
# LLM Invocation
# ---------------------------------------------------------------------------

def _format_prompt(
    risk_score: float,
    recommendation: str,
    budget_analysis: BudgetAgentOutput,
    risk_analysis: RiskAgentOutput,
    deployment_calendar_data: Optional[dict[str, Any]],
    retrieved_policy_documents: Optional[list[dict[str, Any]]],
    user_release_notes: Optional[str],
) -> str:
    """Format user prompt payload with strict isolation of untrusted data."""
    cal = deployment_calendar_data or {}

    policy_context = "None retrieved."
    if retrieved_policy_documents:
        policy_lines = []
        for doc in retrieved_policy_documents:
            policy_lines.append(f"[{doc.get('source')}]:\n{doc.get('content')}")
        policy_context = "\n---\n".join(policy_lines)

    notes = user_release_notes or "None provided."

    return EXPLANATION_USER_PROMPT_TEMPLATE.format(
        risk_score=risk_score,
        recommendation=recommendation,
        budget_status=budget_analysis.status.value,
        budget_summary=budget_analysis.summary,
        budget_evidence="; ".join(budget_analysis.evidence),
        budget_warnings="; ".join(budget_analysis.warnings),
        risk_summary=risk_analysis.risk_summary,
        contributing_factors="; ".join(risk_analysis.contributing_factors),
        historical_evidence="; ".join(risk_analysis.historical_evidence) or "None",
        data_limitations="; ".join(risk_analysis.data_limitations) or "None",
        timing_advice=cal.get("advice", "No calendar restrictions"),
        window_label=cal.get("label", "Standard"),
        retrieved_policy_context=policy_context,
        release_notes=notes,
    )


def generate_explanation(
    *,
    risk_score: float,
    recommendation: str,
    budget_analysis: BudgetAgentOutput,
    risk_analysis: RiskAgentOutput,
    deployment_calendar_data: Optional[dict[str, Any]] = None,
    retrieved_policy_documents: Optional[list[dict[str, Any]]] = None,
    user_release_notes: Optional[str] = None,
    provider: Optional[str] = None,
    model: Optional[str] = None,
    timeout_seconds: float = 6.0,
) -> ExplanationAgentOutput:
    """
    Generate an SRE explanation and practical mitigations using an LLM or fallback.

    Guarantees:
    - Never changes the backend recommendation.
    - Uses bounded timeouts to prevent hanging.
    - Validates structured JSON schema.
    - Falls back gracefully on any failure.
    """
    start_time = time.perf_counter()

    gemini_key = os.environ.get("GEMINI_API_KEY") or os.environ.get("GOOGLE_API_KEY")
    groq_key = os.environ.get("GROQ_API_KEY")
    openai_key = os.environ.get("OPENAI_API_KEY") or groq_key
    selected_provider = (provider or os.environ.get("RELEASEGUARD_LLM_PROVIDER", "auto")).lower()

    if selected_provider == "fallback":
        return generate_fallback_explanation(
            risk_score=risk_score,
            recommendation=recommendation,
            budget_analysis=budget_analysis,
            risk_analysis=risk_analysis,
            deployment_calendar_data=deployment_calendar_data,
            retrieved_policy_documents=retrieved_policy_documents,
            reason="EXPLICIT_FALLBACK",
        )

    # 1. Try Gemini
    if (selected_provider in ("auto", "gemini")) and gemini_key:
        try:
            target_model = model or os.environ.get("RELEASEGUARD_LLM_MODEL", "gemini-2.5-flash")
            from google import genai
            from google.genai import types

            client = genai.Client(api_key=gemini_key)
            user_prompt = _format_prompt(
                risk_score=risk_score,
                recommendation=recommendation,
                budget_analysis=budget_analysis,
                risk_analysis=risk_analysis,
                deployment_calendar_data=deployment_calendar_data,
                retrieved_policy_documents=retrieved_policy_documents,
                user_release_notes=user_release_notes,
            )

            response = client.models.generate_content(
                model=target_model,
                contents=[
                    types.Content(
                        role="user",
                        parts=[types.Part.from_text(text=f"{EXPLANATION_AGENT_SYSTEM_PROMPT}\n\n{user_prompt}")],
                    )
                ],
                config=types.GenerateContentConfig(
                    response_mime_type="application/json",
                    temperature=0.2,
                ),
            )
            raw_text = response.text or "{}"
            parsed = json.loads(raw_text)

            # Validate required fields
            explanation = parsed.get("explanation")
            mitigations = parsed.get("mitigations")
            timing = parsed.get("deployment_timing_advice")
            confidence = parsed.get("confidence_note", "Assessment based on provided telemetry.")

            if not (explanation and isinstance(mitigations, list) and timing):
                raise ValueError("LLM response missing required structured schema fields")

            elapsed_ms = (time.perf_counter() - start_time) * 1000.0
            return ExplanationAgentOutput(
                explanation=explanation,
                mitigations=mitigations,
                deployment_timing_advice=timing,
                confidence_note=confidence,
                is_fallback=False,
                model_name=target_model,
                generation_latency_ms=round(elapsed_ms, 2),
            )
        except Exception as exc:
            logger.warning("Gemini explanation generation failed: %s. Using fallback.", exc)
            if selected_provider == "gemini":
                return generate_fallback_explanation(
                    risk_score=risk_score,
                    recommendation=recommendation,
                    budget_analysis=budget_analysis,
                    risk_analysis=risk_analysis,
                    deployment_calendar_data=deployment_calendar_data,
                    retrieved_policy_documents=retrieved_policy_documents,
                    reason=f"GEMINI_ERROR: {exc}",
                )

    # 2. Try OpenAI / Groq
    if (selected_provider in ("auto", "openai", "groq")) and openai_key:
        try:
            base_url = os.environ.get("OPENAI_BASE_URL")
            if not base_url and (groq_key or selected_provider == "groq" or (openai_key and openai_key.startswith("gsk_"))):
                base_url = "https://api.groq.com/openai/v1"
            default_model = "llama-3.3-70b-versatile" if (groq_key or selected_provider == "groq" or (base_url and "groq" in base_url) or (openai_key and openai_key.startswith("gsk_"))) else "gpt-4o-mini"
            target_model = model or os.environ.get("RELEASEGUARD_LLM_MODEL", default_model)
            from openai import OpenAI

            client = OpenAI(api_key=openai_key, base_url=base_url, timeout=timeout_seconds)
            user_prompt = _format_prompt(
                risk_score=risk_score,
                recommendation=recommendation,
                budget_analysis=budget_analysis,
                risk_analysis=risk_analysis,
                deployment_calendar_data=deployment_calendar_data,
                retrieved_policy_documents=retrieved_policy_documents,
                user_release_notes=user_release_notes,
            )

            resp = client.chat.completions.create(
                model=target_model,
                messages=[
                    {"role": "system", "content": EXPLANATION_AGENT_SYSTEM_PROMPT},
                    {"role": "user", "content": user_prompt},
                ],
                response_format={"type": "json_object"},
                temperature=0.2,
            )
            raw_text = resp.choices[0].message.content or "{}"
            parsed = json.loads(raw_text)

            explanation = parsed.get("explanation")
            mitigations = parsed.get("mitigations")
            timing = parsed.get("deployment_timing_advice")
            confidence = parsed.get("confidence_note", "Assessment based on provided telemetry.")

            if not (explanation and isinstance(mitigations, list) and timing):
                raise ValueError("OpenAI response missing required structured schema fields")

            elapsed_ms = (time.perf_counter() - start_time) * 1000.0
            return ExplanationAgentOutput(
                explanation=explanation,
                mitigations=mitigations,
                deployment_timing_advice=timing,
                confidence_note=confidence,
                is_fallback=False,
                model_name=target_model,
                generation_latency_ms=round(elapsed_ms, 2),
            )
        except Exception as exc:
            logger.warning("OpenAI explanation generation failed: %s. Using fallback.", exc)
            if selected_provider == "openai":
                return generate_fallback_explanation(
                    risk_score=risk_score,
                    recommendation=recommendation,
                    budget_analysis=budget_analysis,
                    risk_analysis=risk_analysis,
                    deployment_calendar_data=deployment_calendar_data,
                    retrieved_policy_documents=retrieved_policy_documents,
                    reason=f"OPENAI_ERROR: {exc}",
                )

    # 3. Default Fallback
    reason = "NO_API_KEY_CONFIGURED" if not (gemini_key or openai_key) else "LLM_PROVIDER_UNAVAILABLE"
    return generate_fallback_explanation(
        risk_score=risk_score,
        recommendation=recommendation,
        budget_analysis=budget_analysis,
        risk_analysis=risk_analysis,
        deployment_calendar_data=deployment_calendar_data,
        retrieved_policy_documents=retrieved_policy_documents,
        reason=reason,
    )
